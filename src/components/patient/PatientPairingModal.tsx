import React, { useState } from 'react';
import { X, Tablet, QrCode, CheckCircle2, ArrowRight, ShieldCheck, AlertCircle } from 'lucide-react';
import { sound } from '../../utils/audio.ts';

interface PatientPairingModalProps {
  isOpen: boolean;
  activePairingCode?: string;
  onPair: (code: string) => Promise<{ success: boolean; error?: string }>;
  onClose: () => void;
}

export const PatientPairingModal: React.FC<PatientPairingModalProps> = ({
  isOpen,
  activePairingCode,
  onPair,
  onClose,
}) => {
  const [code, setCode] = useState(activePairingCode || '');
  const [isLoading, setIsLoading] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [successMessage, setSuccessMessage] = useState<string | null>(null);

  if (!isOpen) return null;

  const handleDigitChange = (val: string) => {
    const cleaned = val.replace(/\D/g, '').slice(0, 6);
    setCode(cleaned);
    setErrorMessage(null);
  };

  const handlePairSubmit = async (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    setErrorMessage(null);
    setSuccessMessage(null);

    const cleanCode = code.replace(/\s+/g, '');
    if (cleanCode.length !== 6) {
      setErrorMessage('Please enter a complete 6-digit pairing code.');
      sound.playChime('alert');
      return;
    }

    setIsLoading(true);
    try {
      const res = await onPair(cleanCode);
      if (res.success) {
        sound.playChime('success');
        setSuccessMessage('Tablet paired successfully with Care Circle!');
        setTimeout(() => {
          onClose();
        }, 800);
      } else {
        sound.playChime('alert');
        setErrorMessage(res.error || 'Invalid or expired pairing code.');
      }
    } catch (err) {
      sound.playChime('alert');
      setErrorMessage(err instanceof Error ? err.message : 'Pairing failed. Please try again.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleUseSuggestedCode = (suggested: string) => {
    setCode(suggested.replace(/\s+/g, ''));
    setErrorMessage(null);
  };

  return (
    <div
      role="dialog"
      aria-modal="true"
      className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm animate-in fade-in duration-200"
    >
      <div className="w-full max-w-md bg-white dark:bg-slate-800 rounded-3xl shadow-2xl border border-[#E2DCD5] dark:border-slate-700 overflow-hidden flex flex-col">
        {/* Header */}
        <div className="p-5 border-b border-[#E2DCD5] dark:border-slate-700 flex items-center justify-between bg-[#FBF9F5] dark:bg-slate-850">
          <div className="flex items-center gap-2.5">
            <div className="w-10 h-10 rounded-xl bg-teal-100 dark:bg-teal-900 text-[#00524d] dark:text-[#5eead4] flex items-center justify-center">
              <Tablet className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-bold text-lg text-[#1E293B] dark:text-slate-100">
                Pair Aita's Tablet
              </h3>
              <p className="text-xs text-[#475569] dark:text-slate-400">
                Link this device to your Family Care Circle
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="w-9 h-9 rounded-full bg-slate-100 dark:bg-slate-700 text-slate-500 hover:text-slate-800 dark:hover:text-white flex items-center justify-center cursor-pointer"
            type="button"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 flex flex-col gap-4">
          <div className="text-center">
            <p className="text-xs text-slate-600 dark:text-slate-300 leading-relaxed mb-4">
              Enter the <strong>6-digit device pairing code</strong> generated by the caregiver in the Setup Wizard (C-02).
            </p>

            {/* 6-Digit input */}
            <form onSubmit={handlePairSubmit} className="flex flex-col items-center gap-4">
              <div className="relative w-full max-w-[280px]">
                <input
                  type="text"
                  inputMode="numeric"
                  pattern="[0-9]*"
                  maxLength={6}
                  value={code}
                  onChange={(e) => handleDigitChange(e.target.value)}
                  placeholder="------"
                  className="w-full py-3 px-4 rounded-2xl border-2 border-slate-300 dark:border-slate-600 bg-slate-50 dark:bg-slate-900 text-center font-mono text-3xl font-bold tracking-widest text-[#00524d] dark:text-[#5eead4] focus:outline-none focus:border-[#00524d]"
                  autoFocus
                />
              </div>

              {activePairingCode && (
                <button
                  type="button"
                  onClick={() => handleUseSuggestedCode(activePairingCode)}
                  className="text-xs text-[#00524d] dark:text-[#5eead4] font-semibold underline hover:opacity-80 cursor-pointer"
                >
                  Fill Active Code: {activePairingCode}
                </button>
              )}

              {errorMessage && (
                <div className="w-full p-3 rounded-xl bg-red-50 dark:bg-red-950/40 border border-red-200 dark:border-red-900 text-xs text-red-700 dark:text-red-300 flex items-center gap-2 text-left">
                  <AlertCircle className="w-4 h-4 shrink-0 text-red-600" />
                  <span>{errorMessage}</span>
                </div>
              )}

              {successMessage && (
                <div className="w-full p-3 rounded-xl bg-emerald-50 dark:bg-emerald-950/40 border border-emerald-200 dark:border-emerald-900 text-xs text-emerald-700 dark:text-emerald-300 flex items-center gap-2 text-left">
                  <CheckCircle2 className="w-4 h-4 shrink-0 text-emerald-600" />
                  <span>{successMessage}</span>
                </div>
              )}

              <button
                type="submit"
                disabled={isLoading || code.length !== 6}
                className="w-full py-3.5 px-4 rounded-2xl bg-[#00524d] hover:bg-[#1e6b65] text-white font-bold text-sm shadow-sm transition-all active:scale-95 cursor-pointer disabled:opacity-50 flex items-center justify-center gap-2 mt-2"
              >
                <span>{isLoading ? 'Pairing Tablet...' : 'Confirm & Pair Device'}</span>
                <ArrowRight className="w-4 h-4" />
              </button>
            </form>
          </div>

          <div className="mt-2 p-3.5 bg-slate-50 dark:bg-slate-750/70 rounded-2xl border border-slate-200 dark:border-slate-700 flex items-center gap-3">
            <ShieldCheck className="w-5 h-5 text-emerald-600 shrink-0" />
            <p className="text-[11px] text-slate-500 dark:text-slate-400 leading-tight">
              Once paired, routine times, memory photos, and personalized calming prompts synchronize automatically to this tablet.
            </p>
          </div>
        </div>
      </div>
    </div>
  );
};
